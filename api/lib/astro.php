/** Greenwich apparent sidereal time (องศา) จาก JD ในมาตรา UT */
function fis_astro_gast(float $jdUt): float
{
    $t = ($jdUt - 2451545.0) / 36525.0;
    $theta0 = 280.46061837 + 360.98564736629 * ($jdUt - 2451545.0)
            + 0.000387933 * $t * $t - $t ** 3 / 38710000.0;

    // equation of the equinoxes: Δψ cos ε
    $nut = fis_astro_nutation($t);
    $theta0 += $nut['dpsi'] * fis_astro_cos($nut['eps']);

    return fis_astro_norm360($theta0);
}

/**
 * สถานะของดวงจันทร์ที่มองจากจุดสังเกต ณ เวลา Unix ที่กำหนด
 * คืน ['alt' => มุมเงย องศา, 'h0' => มุมเงยเกณฑ์ขึ้น/ตก องศา, 'ha' => มุมชั่วโมง องศา]
 *
 * h0 = 0.7275·π − 0.5667° ตาม Meeus บทที่ 15 หมายเหตุท้ายบท
 * ตัวคูณ 0.7275 ชดเชย parallax โดยประมาณ ส่วน 34 ลิปดา (0.5667°) คือการหักเหแสงมาตรฐาน
 * วิธีนี้ทำให้ใช้พิกัด geocentric ได้โดยไม่ต้องแปลงเป็น topocentric เต็มรูปแบบ
 */
function fis_astro_moon_state(float $unix, float $lat, float $lon): array
{
    $jdUt = fis_astro_jd_from_unix($unix);
    $jde  = $jdUt + fis_astro_delta_t($jdUt) / 86400.0;

    $moon = fis_astro_moon($jde);
    $gast = fis_astro_gast($jdUt);

    // มุมชั่วโมงท้องถิ่น: lon เป็นบวกทางตะวันออก ตามมาตรฐานสมัยใหม่ (ไม่ใช่แบบเก่าของ Meeus)
    $ha = fis_astro_norm180($gast + $lon - $moon['ra']);

    $alt = asin(
        fis_astro_sin($lat) * fis_astro_sin($moon['dec'])
            + fis_astro_cos($lat) * fis_astro_cos($moon['dec']) * fis_astro_cos($ha)
    ) * 180.0 / M_PI;

    $h0 = 0.7275 * $moon['parallax_deg'] - 0.5667;

    return ['alt' => $alt, 'h0' => $h0, 'ha' => $ha];
}

// ---------------------------------------------------------------------------
// ค้นหาเวลาเหตุการณ์ด้วยการสุ่มตัวอย่างแล้วบีบช่วง
//
// ทำไมไม่ใช้สูตร interpolation ของ Meeus บทที่ 15 ตรง ๆ:
// สูตรนั้นสมมติว่ามีเหตุการณ์เกิดขึ้นในวันนั้นแล้ววนซ้ำหาคำตอบ ซึ่งลู่เข้าผิดตัวได้
// ในวันที่ "ไม่มีจันทร์ขึ้น" หรือ "ไม่มีจันทร์ตก" — ซึ่งเป็นกรณีที่สัญญาบังคับให้คืน null
// การไล่สุ่มทั้งวันแล้วดูการเปลี่ยนเครื่องหมายบอกได้ตรง ๆ ว่ามีหรือไม่มีเหตุการณ์
// ---------------------------------------------------------------------------

/** ช่วงสุ่มตัวอย่าง 5 นาที — ดวงจันทร์เคลื่อนที่ไม่เกิน ~1.3 องศาต่อช่วง จึงไม่พลาดจุดตัด */
const FIS_ASTRO_STEP_SECONDS = 300.0;

/** ความละเอียดที่บีบช่วงจนพอใจ (วินาที) ละเอียดกว่าที่รายงานจริง (นาที) หนึ่งระดับ */
const FIS_ASTRO_REFINE_SECONDS = 0.5;

/**
 * บีบช่วง [t1, t2] ที่ f เปลี่ยนเครื่องหมายจากลบเป็นบวก ด้วยวิธีแบ่งครึ่ง
 * ใช้แบ่งครึ่งแทน secant เพราะรับประกันว่าลู่เข้าเสมอ และรอบการคำนวณไม่กี่สิบรอบก็เร็วพอ
 */
function fis_astro_bisect(callable $f, float $t1, float $t2): float
{
    $f1 = $f($t1);
    for ($i = 0; $i < 60 && ($t2 - $t1) > FIS_ASTRO_REFINE_SECONDS; $i++) {
        $mid = ($t1 + $t2) / 2.0;
        $fm  = $f($mid);
        if (($f1 < 0.0) === ($fm < 0.0)) {
            $t1 = $mid;
            $f1 = $fm;
        } else {
            $t2 = $mid;
        }
    }
    return ($t1 + $t2) / 2.0;
}

/**
 * หาเวลาจันทร์ขึ้น จันทร์ตก และการผ่านเมริเดียนบน/ล่าง ภายในช่วง [start, end]
 * คืนอาเรย์ค่า Unix timestamp หรือ null ถ้าไม่มีเหตุการณ์นั้นในช่วงเวลาที่ให้
 *
 * ระยะห่างระหว่างจันทร์ขึ้นสองครั้งติดกันคือราว 24 ชม. 50 นาที
 * ดังนั้นในหนึ่งวันปฏิทินจะมีเหตุการณ์แต่ละชนิดได้มากที่สุดหนึ่งครั้ง และมี "ศูนย์ครั้ง" ได้จริง
 */
function fis_astro_moon_events(float $start, float $end, float $lat, float $lon): array
{
    $altDiff = static function (float $ts) use ($lat, $lon): float {
        $s = fis_astro_moon_state($ts, $lat, $lon);
        return $s['alt'] - $s['h0'];
    };
    // มุมชั่วโมงเทียบจุดผ่านเมริเดียนบน (0 องศา) และล่าง (180 องศา)
    $haUpper = static function (float $ts) use ($lat, $lon): float {
        return fis_astro_moon_state($ts, $lat, $lon)['ha'];
    };
    $haLower = static function (float $ts) use ($lat, $lon): float {
        return fis_astro_norm180(fis_astro_moon_state($ts, $lat, $lon)['ha'] - 180.0);
    };

    $result = ['moonrise' => null, 'moonset' => null, 'transit' => null, 'antitransit' => null];

    // คำนวณตำแหน่งดวงจันทร์ครั้งเดียวต่อหนึ่งจุดสุ่ม แล้วดึงทั้งมุมเงยและมุมชั่วโมงจากผลเดียวกัน
    // (ถ้าเรียกผ่าน closure ทั้งสามตัวจะคำนวณซ้ำสามรอบโดยไม่จำเป็น)
    $sample = static function (float $ts) use ($lat, $lon): array {
        $s = fis_astro_moon_state($ts, $lat, $lon);
        return [
            'alt' => $s['alt'] - $s['h0'],
            'up'  => $s['ha'],
            'low' => fis_astro_norm180($s['ha'] - 180.0),
        ];
    };

    $prevTs = $start;
    $prev   = $sample($start);
    $prevAlt = $prev['alt'];
    $prevUp  = $prev['up'];
    $prevLow = $prev['low'];

    for ($ts = $start + FIS_ASTRO_STEP_SECONDS; $ts <= $end + 0.001; $ts += FIS_ASTRO_STEP_SECONDS) {
        $cur    = $sample($ts);
        $curAlt = $cur['alt'];
        $curUp  = $cur['up'];
        $curLow = $cur['low'];

        if ($result['moonrise'] === null && $prevAlt < 0.0 && $curAlt >= 0.0) {
            $result['moonrise'] = fis_astro_bisect($altDiff, $prevTs, $ts);
        }
        if ($result['moonset'] === null && $prevAlt >= 0.0 && $curAlt < 0.0) {
            // กลับเครื่องหมายเพื่อให้ bisect เห็นเป็นการข้ามจากลบไปบวกเหมือนกัน
            $neg = static function (float $t) use ($altDiff): float {
                return -$altDiff($t);
            };
            $result['moonset'] = fis_astro_bisect($neg, $prevTs, $ts);
        }
        // มุมชั่วโมงเพิ่มขึ้นตามเวลา จุดผ่านคือช่วงที่ค่าเปลี่ยนจากลบเป็นบวก
        // เงื่อนไข < 180 กันไม่ให้การกระโดดข้ามขอบ ±180 ถูกนับเป็นจุดตัดหลอก
        if ($result['transit'] === null && $prevUp < 0.0 && $curUp >= 0.0 && ($curUp - $prevUp) < 180.0) {
            $result['transit'] = fis_astro_bisect($haUpper, $prevTs, $ts);
        }
        if ($result['antitransit'] === null && $prevLow < 0.0 && $curLow >= 0.0 && ($curLow - $prevLow) < 180.0) {
            $result['antitransit'] = fis_astro_bisect($haLower, $prevTs, $ts);
        }

        $prevTs  = $ts;
        $prevAlt = $curAlt;
        $prevUp  = $curUp;
        $prevLow = $curLow;
    }

    return $result;
}

