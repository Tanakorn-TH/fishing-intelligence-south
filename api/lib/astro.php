/**
 * เวลาเดือนดับ (New Moon) ครั้งล่าสุดก่อนหรือตรงกับ JDE ที่ให้ — Meeus บทที่ 49
 * รวมทั้งเทอมหลัก 25 เทอม และเทอมแก้จากดาวเคราะห์ A1..A14
 * Meeus ระบุความคลาดเคลื่อนสูงสุด ~17 วินาที ในช่วง ค.ศ. 1980-2020
 */
function fis_astro_previous_new_moon(float $jde): float
{
    // ประมาณค่า k เริ่มต้นจากจำนวนเดือนจันทรคติที่ผ่านไปนับจาก ค.ศ. 2000
    $year = 2000.0 + ($jde - 2451545.0) / 365.25;
    $k = floor(($year - 2000.0) * 12.3685);

    // ถอยหลังจนกว่าจะได้เดือนดับที่อยู่ก่อนเวลาเป้าหมาย แล้วเดินหน้าให้ชิดที่สุด
    for ($guard = 0; $guard < 40; $guard++) {
        $jdeNew = fis_astro_new_moon_at_k($k);
        if ($jdeNew > $jde) {
            $k -= 1.0;
            continue;
        }
        if (fis_astro_new_moon_at_k($k + 1.0) <= $jde) {
            $k += 1.0;
            continue;
        }
        return $jdeNew;
    }
    return fis_astro_new_moon_at_k($k);
}

/** เวลาเดือนดับของดัชนี k (k เป็นจำนวนเต็ม, k=0 คือเดือนดับวันที่ 2000-01-06) */
function fis_astro_new_moon_at_k(float $k): float
{
    $t = $k / 1236.85;

    // (49.1) เวลาเฉลี่ยของจันทร์ดับ
    $jde = 2451550.09766 + 29.530588861 * $k
         + 0.00015437 * $t ** 2
         - 0.000000150 * $t ** 3
         + 0.00000000073 * $t ** 4;

    $e  = 1.0 - 0.002516 * $t - 0.0000074 * $t * $t;
    $e2 = $e * $e;

    $m  = 2.5534 + 29.10535670 * $k - 0.0000014 * $t ** 2 - 0.00000011 * $t ** 3;
    $mp = 201.5643 + 385.81693528 * $k + 0.0107582 * $t ** 2
        + 0.00001238 * $t ** 3 - 0.000000058 * $t ** 4;
    $f  = 160.7108 + 390.67050284 * $k - 0.0016118 * $t ** 2
        - 0.00000227 * $t ** 3 + 0.000000011 * $t ** 4;
    $om = 124.7746 - 1.56375588 * $k + 0.0020672 * $t ** 2 + 0.00000215 * $t ** 3;

    $jde += -0.40720 * fis_astro_sin($mp)
          + 0.17241 * $e * fis_astro_sin($m)
          + 0.01608 * fis_astro_sin(2.0 * $mp)
          + 0.01039 * fis_astro_sin(2.0 * $f)
          + 0.00739 * $e * fis_astro_sin($mp - $m)
          - 0.00514 * $e * fis_astro_sin($mp + $m)
          + 0.00208 * $e2 * fis_astro_sin(2.0 * $m)
          - 0.00111 * fis_astro_sin($mp - 2.0 * $f)
          - 0.00057 * fis_astro_sin($mp + 2.0 * $f)
          + 0.00056 * $e * fis_astro_sin(2.0 * $mp + $m)
          - 0.00042 * fis_astro_sin(3.0 * $mp)
          + 0.00042 * $e * fis_astro_sin($m + 2.0 * $f)
          + 0.00038 * $e * fis_astro_sin($m - 2.0 * $f)
          - 0.00024 * $e * fis_astro_sin(2.0 * $mp - $m)
          - 0.00017 * fis_astro_sin($om)
          - 0.00007 * fis_astro_sin($mp + 2.0 * $m)
          + 0.00004 * fis_astro_sin(2.0 * $mp - 2.0 * $f)
          + 0.00004 * fis_astro_sin(3.0 * $m)
          + 0.00003 * fis_astro_sin($mp + $m - 2.0 * $f)
          + 0.00003 * fis_astro_sin(2.0 * $mp + 2.0 * $f)
          - 0.00003 * fis_astro_sin($mp + $m + 2.0 * $f)
          + 0.00003 * fis_astro_sin($mp - $m + 2.0 * $f)
          - 0.00002 * fis_astro_sin($mp - $m - 2.0 * $f)
          - 0.00002 * fis_astro_sin(3.0 * $mp + $m)
          + 0.00002 * fis_astro_sin(4.0 * $mp);

    // เทอมแก้เพิ่มเติมจากอิทธิพลของดาวเคราะห์ (ตารางท้ายบทที่ 49) รวมกันไม่เกิน ~1 นาที
    $planetary = [
        [299.77 + 0.107408 * $k - 0.009173 * $t * $t, 0.000325],
        [251.88 + 0.016321 * $k, 0.000165],
        [251.83 + 26.651886 * $k, 0.000164],
        [349.42 + 36.412478 * $k, 0.000126],
        [84.66 + 18.206239 * $k, 0.000110],
        [141.74 + 53.303771 * $k, 0.000062],
        [207.14 + 2.453732 * $k, 0.000060],
        [154.84 + 7.306860 * $k, 0.000056],
        [34.52 + 27.261239 * $k, 0.000047],
        [207.19 + 0.121824 * $k, 0.000042],
        [291.34 + 1.844379 * $k, 0.000040],
        [161.72 + 24.198154 * $k, 0.000037],
        [239.56 + 25.513099 * $k, 0.000035],
        [331.55 + 3.592518 * $k, 0.000023],
    ];
    foreach ($planetary as $p) {
        $jde += $p[1] * fis_astro_sin($p[0]);
    }

    return $jde;
}

/**
 * ส่วนสว่างของจานดวงจันทร์ — Meeus บทที่ 48 สูตร (48.2) และ (48.3)
 * คำนวณจากตำแหน่งจริงของดวงอาทิตย์และดวงจันทร์ ไม่ใช่ประมาณจากอายุดวงจันทร์
 * เพราะวงโคจรรีทำให้สองค่านั้นต่างกันได้หลายจุดเปอร์เซ็นต์
 * คืนสัดส่วน 0.0-1.0
 */
function fis_astro_moon_illumination(float $jde): float
{
    $sun  = fis_astro_sun($jde);
    $moon = fis_astro_moon($jde);

    // ψ = มุมห่างเชิงมุมระหว่างดวงอาทิตย์กับดวงจันทร์ที่มองจากโลก
    $cosPsi = fis_astro_sin($sun['dec']) * fis_astro_sin($moon['dec'])
            + fis_astro_cos($sun['dec']) * fis_astro_cos($moon['dec'])
              * fis_astro_cos($sun['ra'] - $moon['ra']);
    $cosPsi = max(-1.0, min(1.0, $cosPsi));
    $psi = acos($cosPsi);

    // i = มุมเฟส (โลก-ดวงจันทร์-ดวงอาทิตย์) ระยะทั้งสองต้องหน่วยเดียวกัน
    $rKm  = $sun['r_au'] * 149597870.7;
    $i = atan2($rKm * sin($psi), $moon['dist_km'] - $rKm * cos($psi));

    return (1.0 + cos($i)) / 2.0;
}

/** ความยาวเฉลี่ยของเดือนจันทรคติ (synodic month) หน่วยวัน — Meeus บทที่ 49 */
const FIS_ASTRO_SYNODIC_MONTH = 29.530588861;

/**
 * ชื่อข้างขึ้นข้างแรมแบบไทยจากอายุดวงจันทร์
 *
 * ที่มาของการแปลง: แบ่งหนึ่งรอบจันทรคติเป็น 30 ค่ำเท่า ๆ กัน
 *   ค่ำที่ 1-15  = "ขึ้น n ค่ำ"  (เดือนดับ -> เดือนเพ็ญ)
 *   ค่ำที่ 16-30 = "แรม n-15 ค่ำ" (เดือนเพ็ญ -> เดือนดับ)
 *
 * ข้อจำกัดสำคัญ: นี่คือค่ำ "ตามดาราศาสตร์จริง" ไม่ใช่ปฏิทินจันทรคติไทยทางการ
 * ปฏิทินไทยเป็นปฏิทินคำนวณตามคัมภีร์สุริยยาตร์ มีเดือนขาด (แรม 14 ค่ำ) และการปรับอธิกวาร
 * จึงอาจต่างจากค่าที่นี่ได้ประมาณ 1 วัน ผู้ใช้ที่ต้องการวันพระต้องดูปฏิทินทางการ
 */
function fis_astro_thai_phase_name(float $ageDays): string
{
    $fraction = $ageDays / FIS_ASTRO_SYNODIC_MONTH;
    $fraction -= floor($fraction);

    $day = (int) floor($fraction * 30.0) + 1;
    if ($day < 1) {
        $day = 1;
    }
    if ($day > 30) {
        $day = 30;
    }

    return $day <= 15 ? 'ขึ้น ' . $day . ' ค่ำ' : 'แรม ' . ($day - 15) . ' ค่ำ';
}

/**
 * สรุปข้างขึ้นข้างแรม ณ เวลา Unix ที่กำหนด
 * คืน ['age_days', 'illumination', 'phase_name_th']
 */
function fis_astro_moon_phase(float $unix): array
{
    $jde = fis_astro_jde_from_unix($unix);

    $newMoon = fis_astro_previous_new_moon($jde);
    $age = $jde - $newMoon;
    if ($age < 0.0) {
        $age = 0.0; // กันค่าติดลบจากการปัดเศษเมื่ออยู่ตรงจุดเดือนดับพอดี
    }

    return [
        'age_days'      => $age,
        'illumination'  => fis_astro_moon_illumination($jde),
        'phase_name_th' => fis_astro_thai_phase_name($age),
    ];
}
