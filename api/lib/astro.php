/** ทำให้มุมอยู่ในช่วง [0, 360) */
function fis_astro_norm360(float $deg): float
{
    $d = fmod($deg, 360.0);
    return $d < 0.0 ? $d + 360.0 : $d;
}

/** ทำให้มุมอยู่ในช่วง [-180, 180) ใช้กับมุมชั่วโมงเพื่อหาจุดตัดศูนย์ */
function fis_astro_norm180(float $deg): float
{
    return fis_astro_norm360($deg + 180.0) - 180.0;
}

function fis_astro_sin(float $deg): float
{
    return sin($deg * M_PI / 180.0);
}

function fis_astro_cos(float $deg): float
{
    return cos($deg * M_PI / 180.0);
}

/** Julian Day (UT) จาก Unix timestamp — 1970-01-01T00:00:00Z ตรงกับ JD 2440587.5 */
function fis_astro_jd_from_unix(float $unix): float
{
    return $unix / 86400.0 + 2440587.5;
}

/**
 * ΔT = TT - UT หน่วยวินาที
 * พหุนามของ Espenak & Meeus (NASA Eclipse Web Site) ซึ่งเป็นฉบับปรับปรุงของ Meeus บทที่ 10
 * ค่านี้มีผลน้อยมาก: คลาด 10 วินาทีทำให้ตำแหน่งดวงจันทร์เพี้ยนราว 5 พิลิปดาเท่านั้น
 */
function fis_astro_delta_t(float $jdUt): float
{
    // ปีแบบทศนิยมโดยประมาณ พอสำหรับใช้เลือกช่วงพหุนาม
    $y = 2000.0 + ($jdUt - 2451545.0) / 365.25;

    if ($y >= 2005.0 && $y < 2050.0) {
        $t = $y - 2000.0;
        return 62.92 + 0.32217 * $t + 0.005589 * $t * $t;
    }
    if ($y >= 1986.0 && $y < 2005.0) {
        $t = $y - 2000.0;
        return 63.86 + 0.3345 * $t - 0.060374 * $t ** 2 + 0.0017275 * $t ** 3
             + 0.000651814 * $t ** 4 + 0.00002373599 * $t ** 5;
    }
    if ($y >= 2050.0 && $y < 2150.0) {
        return -20.0 + 32.0 * (($y - 1820.0) / 100.0) ** 2 - 0.5628 * (2150.0 - $y);
    }
    // นอกช่วงที่มีพหุนามเจาะจง ใช้สูตรระยะยาว — ความแม่นต่ำ แต่ไม่ทำให้โปรแกรมพัง
    $u = ($y - 1820.0) / 100.0;
    return -20.0 + 32.0 * $u * $u;
}

/** Julian Ephemeris Day (มาตราเวลา TT) จาก Unix timestamp */
function fis_astro_jde_from_unix(float $unix): float
{
    $jdUt = fis_astro_jd_from_unix($unix);
    return $jdUt + fis_astro_delta_t($jdUt) / 86400.0;
}

