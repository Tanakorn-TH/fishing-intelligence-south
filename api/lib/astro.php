// Nutation และความเอียงของแกนโลก — Meeus บทที่ 22 (ตารางย่อ)
// ---------------------------------------------------------------------------

/**
 * คืน ['dpsi' => Δψ องศา, 'deps' => Δε องศา, 'eps' => ความเอียงจริง องศา]
 * ใช้เฉพาะ 4 เทอมหลักตามที่ Meeus ระบุว่าให้ความแม่น 0.5 พิลิปดา
 * ซึ่งเล็กกว่าความคลาดเคลื่อนของตำแหน่งดวงจันทร์ (~10") มาก จึงไม่ใช่คอขวด
 */
function fis_astro_nutation(float $t): array
{
    $omega = 125.04452 - 1934.136261 * $t + 0.0020708 * $t * $t + $t ** 3 / 450000.0;
    $lSun  = 280.4665 + 36000.7698 * $t;   // ลองจิจูดเฉลี่ยดวงอาทิตย์
    $lMoon = 218.3165 + 481267.8813 * $t;  // ลองจิจูดเฉลี่ยดวงจันทร์

    // Δψ และ Δε ในหน่วยพิลิปดา แล้วหารด้วย 3600 เป็นองศา
    $dpsi = -17.20 * fis_astro_sin($omega)
          - 1.32 * fis_astro_sin(2.0 * $lSun)
          - 0.23 * fis_astro_sin(2.0 * $lMoon)
          + 0.21 * fis_astro_sin(2.0 * $omega);

    $deps = 9.20 * fis_astro_cos($omega)
          + 0.57 * fis_astro_cos(2.0 * $lSun)
          + 0.10 * fis_astro_cos(2.0 * $lMoon)
          - 0.09 * fis_astro_cos(2.0 * $omega);

    // ความเอียงเฉลี่ย ε0 — Meeus (22.2) เขียนเป็น องศา ลิปดา พิลิปดา
    $eps0 = 23.0 + 26.0 / 60.0 + 21.448 / 3600.0
          - (46.8150 * $t + 0.00059 * $t * $t - 0.001813 * $t ** 3) / 3600.0;

    return [
        'dpsi' => $dpsi / 3600.0,
        'deps' => $deps / 3600.0,
        'eps'  => $eps0 + $deps / 3600.0,
    ];
}

// ---------------------------------------------------------------------------
// ตำแหน่งดวงอาทิตย์ — Meeus บทที่ 25 (สูตรความละเอียดต่ำ ~0.01 องศา)
// ใช้เพื่อคำนวณส่วนสว่างของดวงจันทร์เท่านั้น ความแม่นระดับนี้เพียงพอ
// ---------------------------------------------------------------------------

/** คืน ['ra' => องศา, 'dec' => องศา, 'r_au' => ระยะโลก-ดวงอาทิตย์ หน่วย AU] */
function fis_astro_sun(float $jde): array
{
    $t = ($jde - 2451545.0) / 36525.0;

    $l0 = 280.46646 + 36000.76983 * $t + 0.0003032 * $t * $t;      // ลองจิจูดเฉลี่ย
    $m  = 357.52911 + 35999.05029 * $t - 0.0001537 * $t * $t;      // anomaly เฉลี่ย
    $e  = 0.016708634 - 0.000042037 * $t - 0.0000001267 * $t * $t; // ความรีวงโคจรโลก

    // equation of the center
    $c = (1.914602 - 0.004817 * $t - 0.000014 * $t * $t) * fis_astro_sin($m)
       + (0.019993 - 0.000101 * $t) * fis_astro_sin(2.0 * $m)
       + 0.000289 * fis_astro_sin(3.0 * $m);

    $trueLon = $l0 + $c;
    $nu      = $m + $c;
    $rAu     = 1.000001018 * (1.0 - $e * $e) / (1.0 + $e * fis_astro_cos($nu));

    // ลองจิจูดปรากฏ: แก้ nutation + aberration
    $omega  = 125.04 - 1934.136 * $t;
    $lambda = $trueLon - 0.00569 - 0.00478 * fis_astro_sin($omega);

    $nut = fis_astro_nutation($t);
    // Meeus แนะนำให้บวก 0.00256 cos Ω เมื่อใช้ลองจิจูดปรากฏคู่กับความเอียง
    $eps = $nut['eps'] + 0.00256 * fis_astro_cos($omega);

    // (13.3) และ (13.4) โดยที่ละติจูดสุริยวิถีของดวงอาทิตย์ ~ 0
    $ra = atan2(fis_astro_cos($eps) * fis_astro_sin($lambda), fis_astro_cos($lambda))
        * 180.0 / M_PI;
    $dec = asin(fis_astro_sin($eps) * fis_astro_sin($lambda)) * 180.0 / M_PI;

    return ['ra' => fis_astro_norm360($ra), 'dec' => $dec, 'r_au' => $rAu];
}

