/**
 * ตำแหน่งปรากฏของดวงจันทร์ (geocentric) ณ เวลา JDE
 * คืน ['ra','dec' องศา, 'dist_km', 'parallax_deg', 'lambda','beta' องศา]
 * ความคลาดเคลื่อนตามที่ Meeus ระบุ: ลองจิจูด ~10" ละติจูด ~4" ระยะทาง ~2 กม.
 */
function fis_astro_moon(float $jde): array
{
    $t = ($jde - 2451545.0) / 36525.0;

    // (47.1)-(47.5) อาร์กิวเมนต์เฉลี่ย
    $lp = 218.3164477 + 481267.88123421 * $t - 0.0015786 * $t ** 2
        + $t ** 3 / 538841.0 - $t ** 4 / 65194000.0;              // L' ลองจิจูดเฉลี่ย
    $d  = 297.8501921 + 445267.1114034 * $t - 0.0018819 * $t ** 2
        + $t ** 3 / 545868.0 - $t ** 4 / 113065000.0;             // D  elongation เฉลี่ย
    $m  = 357.5291092 + 35999.0502909 * $t - 0.0001536 * $t ** 2
        + $t ** 3 / 24490000.0;                                   // M  anomaly ดวงอาทิตย์
    $mp = 134.9633964 + 477198.8675055 * $t + 0.0087414 * $t ** 2
        + $t ** 3 / 69699.0 - $t ** 4 / 14712000.0;               // M' anomaly ดวงจันทร์
    $f  = 93.2720950 + 483202.0175233 * $t - 0.0036539 * $t ** 2
        - $t ** 3 / 3526000.0 + $t ** 4 / 863310000.0;            // F  argument of latitude

    // เทอมเพิ่มเติมจากอิทธิพลของดาวศุกร์ ดาวพฤหัส และการแบนของโลก
    $a1 = 119.75 + 131.849 * $t;
    $a2 = 53.09 + 479264.290 * $t;
    $a3 = 313.45 + 481266.484 * $t;

    // E แก้ความรีของวงโคจรโลกที่ค่อย ๆ ลดลง ใช้กับเทอมที่มี M
    $e  = 1.0 - 0.002516 * $t - 0.0000074 * $t * $t;
    $e2 = $e * $e;

    $sumL = 0.0;
    $sumR = 0.0;
    foreach (fis_astro_moon_table_lr() as $row) {
        $arg = $row[0] * $d + $row[1] * $m + $row[2] * $mp + $row[3] * $f;
        $mAbs = abs($row[1]);
        $factor = $mAbs === 1 ? $e : ($mAbs === 2 ? $e2 : 1.0);
        $sumL += $row[4] * $factor * fis_astro_sin($arg);
        $sumR += $row[5] * $factor * fis_astro_cos($arg);
    }

    $sumB = 0.0;
    foreach (fis_astro_moon_table_b() as $row) {
        $arg = $row[0] * $d + $row[1] * $m + $row[2] * $mp + $row[3] * $f;
        $mAbs = abs($row[1]);
        $factor = $mAbs === 1 ? $e : ($mAbs === 2 ? $e2 : 1.0);
        $sumB += $row[4] * $factor * fis_astro_sin($arg);
    }

    // เทอมบวกเพิ่มท้ายบทที่ 47
    $sumL += 3958.0 * fis_astro_sin($a1)
           + 1962.0 * fis_astro_sin($lp - $f)
           + 318.0 * fis_astro_sin($a2);
    $sumB += -2235.0 * fis_astro_sin($lp)
           + 382.0 * fis_astro_sin($a3)
           + 175.0 * fis_astro_sin($a1 - $f)
           + 175.0 * fis_astro_sin($a1 + $f)
           + 127.0 * fis_astro_sin($lp - $mp)
           - 115.0 * fis_astro_sin($lp + $mp);

    $lambda = fis_astro_norm360($lp + $sumL / 1000000.0); // ลองจิจูดสุริยวิถีจริง
    $beta   = $sumB / 1000000.0;                          // ละติจูดสุริยวิถี
    $dist   = 385000.56 + $sumR / 1000.0;                 // ระยะทางเป็นกิโลเมตร

    // parallax แนวราบ (47.รูปแบบท้ายบท) — รัศมีโลกเชิงศูนย์สูตร 6378.14 กม.
    $parallax = asin(6378.14 / $dist) * 180.0 / M_PI;

    // ลองจิจูดปรากฏ = ลองจิจูดจริง + nutation ในลองจิจูด
    $nut = fis_astro_nutation($t);
    $lambdaApp = $lambda + $nut['dpsi'];
    $eps = $nut['eps'];

    // (13.3) และ (13.4) แปลงเป็นพิกัดศูนย์สูตร
    $ra = atan2(
        fis_astro_sin($lambdaApp) * fis_astro_cos($eps)
            - tan($beta * M_PI / 180.0) * fis_astro_sin($eps),
        fis_astro_cos($lambdaApp)
    ) * 180.0 / M_PI;

    $dec = asin(
        fis_astro_sin($beta) * fis_astro_cos($eps)
            + fis_astro_cos($beta) * fis_astro_sin($eps) * fis_astro_sin($lambdaApp)
    ) * 180.0 / M_PI;

    return [
        'ra'           => fis_astro_norm360($ra),
        'dec'          => $dec,
        'dist_km'      => $dist,
        'parallax_deg' => $parallax,
        'lambda'       => $lambdaApp,
        'beta'         => $beta,
    ];
}

